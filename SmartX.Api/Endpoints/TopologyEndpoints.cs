using SmartX.Api.DataStructures;
using SmartX.Api.Models;
using SmartX.Api.Services;

namespace SmartX.Api.Endpoints;

/// <summary>
/// REST endpoints for the Part 3 Network Topology feature.
///
/// Provides:
/// - GET  /api/topology                       — full graph (nodes + edges)
/// - GET  /api/topology/traverse/bfs?start=ID — BFS from a node
/// - GET  /api/topology/traverse/dfs?start=ID — DFS from a node
/// - GET  /api/topology/path?from=ID&to=ID    — shortest hop path
/// - GET  /api/topology/mst/prim?start=ID     — Prim's MST
/// - GET  /api/topology/mst/kruskal           — Kruskal's MST
/// - GET  /api/topology/unreachable?start=ID  — nodes not reachable from start
/// - GET  /api/topology/telemetry-range?deviceId=ID&from=ISO&to=ISO[&metric=M]
/// </summary>
public static class TopologyEndpoints
{
    public static void MapTopologyEndpoints(this WebApplication app)
    {
        // ?????????????????????????????????????????????????????????????
        // Full graph (nodes + edges)
        // ?????????????????????????????????????????????????????????????
        app.MapGet("/api/topology", (TopologyStore store) =>
        {
            var graph = store.Graph;

            var dto = new TopologyGraphDto
            {
                Nodes = graph.GetAllNodes().Select(n => new TopologyNodeDto
                {
                    Id = n.Id,
                    MacAddress = n.MacAddress,
                    Label = n.Label,
                    Category = n.Category,
                    IsOnline = n.IsOnline,
                    X = n.X,
                    Y = n.Y,
                    IsGateway = n.Id.Equals(TopologyStore.GatewayId,
                        StringComparison.OrdinalIgnoreCase)
                }).ToList(),

                Edges = graph.GetAllEdges().Select(e => new TopologyEdgeDto
                {
                    FromId = e.FromId,
                    ToId = e.ToId,
                    Weight = e.Weight,
                    SignalStrengthDbm = e.SignalStrengthDbm
                }).ToList(),

                NodeCount = graph.NodeCount,
                EdgeCount = graph.EdgeCount
            };

            return Results.Ok(dto);
        });

        // ?????????????????????????????????????????????????????????????
        // BFS traversal
        // ?????????????????????????????????????????????????????????????
        app.MapGet("/api/topology/traverse/bfs", (string? start, TopologyStore store) =>
        {
            var startId = string.IsNullOrWhiteSpace(start)
                ? TopologyStore.GatewayId
                : start;

            if (!store.Graph.ContainsNode(startId))
            {
                return Results.NotFound(new
                {
                    success = false,
                    error = $"Node '{startId}' not found in topology."
                });
            }

            var bfs = GraphTraversal.Bfs(store.Graph, startId);

            return Results.Ok(new TraversalResultDto
            {
                StartNode = bfs.StartNode,
                VisitOrder = bfs.VisitOrder,
                HopsFromStart = bfs.HopsFromStart,
                Unreachable = bfs.Unreachable,
                Algorithm = "BFS"
            });
        });

        // ?????????????????????????????????????????????????????????????
        // DFS traversal
        // ?????????????????????????????????????????????????????????????
        app.MapGet("/api/topology/traverse/dfs", (string? start, TopologyStore store) =>
        {
            var startId = string.IsNullOrWhiteSpace(start)
                ? TopologyStore.GatewayId
                : start;

            if (!store.Graph.ContainsNode(startId))
            {
                return Results.NotFound(new
                {
                    success = false,
                    error = $"Node '{startId}' not found in topology."
                });
            }

            var dfs = GraphTraversal.Dfs(store.Graph, startId);

            return Results.Ok(new TraversalResultDto
            {
                StartNode = dfs.StartNode,
                VisitOrder = dfs.VisitOrder,
                HopsFromStart = dfs.HopsFromStart,
                Unreachable = dfs.Unreachable,
                Algorithm = "DFS"
            });
        });

        // ?????????????????????????????????????????????????????????????
        // Shortest hop path
        // ?????????????????????????????????????????????????????????????
        app.MapGet("/api/topology/path", (string from, string to, TopologyStore store) =>
        {
            if (string.IsNullOrWhiteSpace(from) || string.IsNullOrWhiteSpace(to))
            {
                return Results.BadRequest(new
                {
                    success = false,
                    error = "Both 'from' and 'to' parameters are required."
                });
            }

            var path = GraphTraversal.FindShortestPath(store.Graph, from, to);

            return Results.Ok(new PathResultDto
            {
                FromId = from,
                ToId = to,
                Path = path ?? new List<string>(),
                HopCount = path is null ? 0 : Math.Max(0, path.Count - 1),
                Found = path is not null
            });
        });

        // ?????????????????????????????????????????????????????????????
        // Prim's MST
        // ?????????????????????????????????????????????????????????????
        app.MapGet("/api/topology/mst/prim", (string? start, TopologyStore store) =>
        {
            var startId = string.IsNullOrWhiteSpace(start)
                ? TopologyStore.GatewayId
                : start;

            if (!store.Graph.ContainsNode(startId))
            {
                return Results.NotFound(new
                {
                    success = false,
                    error = $"Node '{startId}' not found in topology."
                });
            }

            var mst = MinimumSpanningTree.Prim(store.Graph, startId);

            return Results.Ok(new MstResultDto
            {
                Algorithm = mst.Algorithm,
                Edges = mst.Edges.Select(e => new MstEdgeDto
                {
                    FromId = e.FromId,
                    ToId = e.ToId,
                    Weight = e.Weight
                }).ToList(),
                TotalWeight = mst.TotalWeight,
                NodeCount = mst.IncludedNodes.Count,
                EdgeCount = mst.Edges.Count
            });
        });

        // ?????????????????????????????????????????????????????????????
        // Kruskal's MST
        // ?????????????????????????????????????????????????????????????
        app.MapGet("/api/topology/mst/kruskal", (TopologyStore store) =>
        {
            var mst = MinimumSpanningTree.Kruskal(store.Graph);

            return Results.Ok(new MstResultDto
            {
                Algorithm = mst.Algorithm,
                Edges = mst.Edges.Select(e => new MstEdgeDto
                {
                    FromId = e.FromId,
                    ToId = e.ToId,
                    Weight = e.Weight
                }).ToList(),
                TotalWeight = mst.TotalWeight,
                NodeCount = mst.IncludedNodes.Count,
                EdgeCount = mst.Edges.Count
            });
        });

        // ?????????????????????????????????????????????????????????????
        // Unreachable nodes from a start point
        // ?????????????????????????????????????????????????????????????
        app.MapGet("/api/topology/unreachable", (string? start, TopologyStore store) =>
        {
            var startId = string.IsNullOrWhiteSpace(start)
                ? TopologyStore.GatewayId
                : start;

            if (!store.Graph.ContainsNode(startId))
            {
                return Results.NotFound(new
                {
                    success = false,
                    error = $"Node '{startId}' not found in topology."
                });
            }

            var unreachable = GraphTraversal.FindUnreachable(store.Graph, startId);

            return Results.Ok(new
            {
                success = true,
                startNode = startId,
                unreachableCount = unreachable.Count,
                unreachableNodes = unreachable
            });
        });

        // ?????????????????????????????????????????????????????????????
        // AVL-backed telemetry range query
        // ?????????????????????????????????????????????????????????????
        app.MapGet("/api/topology/telemetry-range",
            (string deviceId, DateTime from, DateTime to, string? metric,
             TelemetryRangeService rangeService) =>
            {
                if (string.IsNullOrWhiteSpace(deviceId))
                {
                    return Results.BadRequest(new
                    {
                        success = false,
                        error = "deviceId is required."
                    });
                }

                if (to < from)
                {
                    return Results.BadRequest(new
                    {
                        success = false,
                        error = "'to' must be greater than or equal to 'from'."
                    });
                }

                var readings = rangeService.GetRange(deviceId, metric, from, to);

                return Results.Ok(new TelemetryRangeResultDto
                {
                    DeviceId = deviceId,
                    Metric = metric,
                    From = from,
                    To = to,
                    Readings = readings,
                    Count = readings.Count,
                    TreeHeight = rangeService.GetTreeHeight(deviceId),
                    TreeValueCount = rangeService.GetTotalValueCount()
                });
            });

        // ?????????????????????????????????????????????????????????????
        // Diagnostics — AVL tree state per device
        // ?????????????????????????????????????????????????????????????
        app.MapGet("/api/topology/avl-stats", (TelemetryRangeService rangeService) =>
        {
            var devices = rangeService.GetTrackedDevices();

            return Results.Ok(new
            {
                success = true,
                totalValues = rangeService.GetTotalValueCount(),
                deviceCount = devices.Count,
                devices = devices.Select(d => new
                {
                    deviceId = d,
                    treeHeight = rangeService.GetTreeHeight(d)
                }).ToList()
            });
        });
    }
}